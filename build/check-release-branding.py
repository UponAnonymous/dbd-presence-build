#!/usr/bin/env python3
"""Fails if a release payload mentions the AI tooling used to build it (owner requirement, RELEASE_CHECKLIST §9).

The shipped app (binaries, resources, README, notices, installer metadata) must show no sign of Claude/Anthropic
or AI-assistant credits. Development files in the repository are out of scope; this checks only what users get.

Usage: python3 build/check-release-branding.py <folder-or-file> [...]
Scans every file (text and binary, ASCII and UTF-16) case-insensitively. Exit 1 lists each hit with context.
"""
import pathlib
import re
import sys

TERMS = ["claude", "anthropic", "co-authored-by", "generated with claude", "generated by claude"]
PATTERN = re.compile("|".join(re.escape(t) for t in TERMS), re.IGNORECASE)
# Game vocabulary that contains a term by coincidence (the survivor Claudette Morel). These exact words are blanked
# before matching; any other occurrence of a term still fails the check.
ALLOWED_WORDS = re.compile(r"claudette", re.IGNORECASE)


def scan_bytes(data: bytes):
    hits = []
    for text in (data.decode("latin-1"), data.decode("utf-16-le", errors="ignore"), data[1:].decode("utf-16-le", errors="ignore")):
        text = ALLOWED_WORDS.sub(lambda m: "." * len(m.group(0)), text)
        for match in PATTERN.finditer(text):
            start = max(0, match.start() - 40)
            context = re.sub(r"[^\x20-\x7e]", ".", text[start:match.end() + 40])
            hits.append(context)
    return hits


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2

    files = []
    for arg in argv[1:]:
        path = pathlib.Path(arg)
        files.extend(p for p in path.rglob("*") if p.is_file()) if path.is_dir() else files.append(path)

    problems = 0
    for file in files:
        for context in scan_bytes(file.read_bytes()):
            problems += 1
            print(f"{file}: ...{context}...")

    if problems:
        print(f"Release branding check FAILED: {problems} mention(s) of AI tooling in {len(files)} scanned files.")
        return 1

    print(f"Release branding check OK: {len(files)} files, no mention of AI tooling.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
