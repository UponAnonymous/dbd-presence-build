// Converts the small Markdown subset used by docs/legal/*.md (headings, paragraphs, bullet lists, bold, inline code,
// links) into HTML. All text is escaped; only https: and mailto: link targets survive. Pure functions, no I/O, so the
// Worker tests can run them. Used by scripts/build-legal.mjs, which writes src/legal-pages.ts.

const ESCAPES = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };

/** Escapes text for both element content and double-quoted attribute values. */
export function escapeHtml(text) {
  return text.replace(/[&<>"']/g, (c) => ESCAPES[c]);
}

/** The target if it is an https: or mailto: URL without whitespace or control characters; otherwise null. */
export function safeHref(target) {
  const href = target.trim();
  // eslint-disable-next-line no-control-regex
  if (/[\s\u0000-\u001f\u007f]/.test(href)) return null;
  if (/^https:\/\/[^/?#]/i.test(href)) return href;
  if (/^mailto:[^\s]+$/i.test(href)) return href;
  return null;
}

const INLINE = /`([^`]+)`|\*\*(.+?)\*\*|\[([^\]]+)\]\(([^)\s]*)\)/;

/** Renders inline Markdown. `allowLinks` is false inside link text so links never nest. */
export function renderInline(text, allowLinks = true) {
  let out = "";
  let rest = text;
  while (rest.length > 0) {
    const m = INLINE.exec(rest);
    if (!m) {
      out += escapeHtml(rest);
      break;
    }
    out += escapeHtml(rest.slice(0, m.index));
    rest = rest.slice(m.index + m[0].length);
    if (m[1] !== undefined) {
      out += `<code>${escapeHtml(m[1])}</code>`;
    } else if (m[2] !== undefined) {
      out += `<strong>${renderInline(m[2], allowLinks)}</strong>`;
    } else {
      const href = allowLinks ? safeHref(m[4]) : null;
      const label = renderInline(m[3], false);
      out += href === null ? label : `<a href="${escapeHtml(href)}" rel="noopener noreferrer">${label}</a>`;
    }
  }
  return out;
}

function renderList(items) {
  // items: { depth, text }[]; depth is the indent in steps of two spaces.
  let html = "";
  const open = [];
  const base = items[0].depth;
  for (const item of items) {
    const depth = Math.max(item.depth, base);
    if (open.length === 0) {
      html += "<ul>";
      open.push(depth);
    } else if (depth > open[open.length - 1]) {
      html += "<ul>";
      open.push(depth);
    } else {
      html += "</li>";
      while (open.length > 1 && depth < open[open.length - 1]) {
        open.pop();
        html += "</ul></li>";
      }
    }
    html += `<li>${renderInline(item.text)}`;
  }
  while (open.length > 0) {
    open.pop();
    html += "</li></ul>";
  }
  return html;
}

/** Renders a document. Returns the page title (the first `# ` heading) and the body HTML (without that heading). */
export function renderMarkdown(markdown) {
  const lines = markdown.replace(/\r\n?/g, "\n").split("\n");
  let title = "";
  let html = "";
  let paragraph = [];
  let list = [];

  const flushParagraph = () => {
    if (paragraph.length > 0) html += `<p>${renderInline(paragraph.join(" "))}</p>\n`;
    paragraph = [];
  };
  const flushList = () => {
    if (list.length > 0) html += `${renderList(list)}\n`;
    list = [];
  };

  for (const line of lines) {
    if (line.trim() === "") {
      flushParagraph();
      flushList();
      continue;
    }
    const heading = /^(#{1,3}) +(.+?) *$/.exec(line);
    if (heading) {
      flushParagraph();
      flushList();
      if (heading[1].length === 1 && title === "") title = heading[2];
      else html += `<h${heading[1].length}>${renderInline(heading[2])}</h${heading[1].length}>\n`;
      continue;
    }
    const bullet = /^( *)[-*] +(.+?) *$/.exec(line);
    if (bullet) {
      flushParagraph();
      list.push({ depth: Math.floor(bullet[1].length / 2), text: bullet[2] });
      continue;
    }
    if (list.length > 0 && /^ +\S/.test(line)) {
      list[list.length - 1].text += ` ${line.trim()}`;
      continue;
    }
    flushList();
    paragraph.push(line.trim());
  }
  flushParagraph();
  flushList();
  if (title === "") throw new Error("The document has no top-level heading.");
  return { title, html };
}

/** The exact text of src/legal-pages.ts for the two documents. */
export function renderLegalModule(privacyMarkdown, termsMarkdown) {
  const privacy = renderMarkdown(privacyMarkdown);
  const terms = renderMarkdown(termsMarkdown);
  const page = (p) => `{ title: ${JSON.stringify(p.title)}, body: ${JSON.stringify(p.html)} }`;
  return [
    "// GENERATED by scripts/build-legal.mjs from docs/legal/privacy-notice.md and docs/legal/terms-of-use.md. Do not edit by hand:",
    "// run `npm run build-legal` in service/ after changing either document (test/legal.test.ts fails while this file is stale).",
    "",
    "export interface LegalPage {",
    "  readonly title: string;",
    "  /** HTML-escaped body markup (headings, paragraphs, lists); the page shell is in routes/legal.ts. */",
    "  readonly body: string;",
    "}",
    "",
    `export const PRIVACY_PAGE: LegalPage = ${page(privacy)};`,
    "",
    `export const TERMS_PAGE: LegalPage = ${page(terms)};`,
    "",
  ].join("\n");
}
