// Provisioning for the deploy workflow (.github/workflows/deploy-service.yml). Plain Node, no dependencies beyond
// wrangler in service/node_modules. Every step is idempotent: it creates only what is missing and never replaces an
// existing secret unless asked to rotate one that may be rotated (scripts/provision-plan.mjs has the rules).
//
//   node scripts/provision.mjs resources   --env staging [--create] [--dry-run] [--state DIR]
//   node scripts/provision.mjs secrets     --env staging [--create] [--rotate --run-number N] [--dry-run] [--assume-existing A,B] [--state DIR]
//   node scripts/provision.mjs workers-dev --env staging [--dry-run] [--state DIR]
//   node scripts/provision.mjs pages       --env staging [--create] [--dry-run] [--state DIR]
//   node scripts/provision.mjs check-config <response body file> [--keys <public-keys json>]
//   node scripts/provision.mjs check-dns   [--smoke FILE]   (appeal.arcavale.com must still be A 207.244.229.132)
//   node scripts/provision.mjs summary     --env staging [--state DIR] [--smoke FILE] [--outcome step=result ...]
//
// Cloudflare is reached with CLOUDFLARE_API_TOKEN and CLOUDFLARE_ACCOUNT_ID from the environment (never printed).
// --dry-run makes no network call and changes nothing in Cloudflare; it shows what would happen.
// Secret values are generated by scripts/new-secret.mjs, piped into `wrangler secret put` on standard input, masked
// in the GitHub log and never written to a file or to standard output.

import { spawnSync } from "node:child_process";
import { Resolver } from "node:dns/promises";
import { appendFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { experimental_readRawConfig, unstable_readConfig } from "wrangler";
import { BACKUP_GUIDE, BACKUP_LOCK_DAYS, BACKUP_RETENTION_DAYS, backupBucketName, backupLifecycleRule, backupLockRule } from "./backup-plan.mjs";
import { cf, describe, findDatabase, hasCode, must } from "./cloudflare-api.mjs";
import {
  AUDIT_BINDING,
  AUDIT_DAYS,
  D1_LOCATION,
  PAGES_PROJECTS,
  PROTECTED_RECORD,
  assertEnvironment,
  auditLifecycleRule,
  auditLockRule,
  configDifferences,
  inspectConfigResponse,
  parseSmokeResults,
  planLifecycleRules,
  planLockRules,
  planSecrets,
  publicKeyFromGeneratorOutput,
  readyToDeploy,
  renderSummary,
  resourcesFromConfig,
  trustedKeyEntries,
  valuesToMask,
  withDatabaseId,
} from "./provision-plan.mjs";

const serviceDir = join(import.meta.dirname, "..");
const panelDir = join(serviceDir, "..", "panel");
const wranglerBin = join(serviceDir, "node_modules", "wrangler", "bin", "wrangler.js");
const newSecretScript = join(serviceDir, "scripts", "new-secret.mjs");
const inActions = process.env.GITHUB_ACTIONS === "true";
const DRY_RUN_DATABASE_ID = "00000000-0000-4000-8000-000000000000";

// ---------------------------------------------------------------------------------------------------------------
// Arguments, state and output

const args = process.argv.slice(2);
const command = args[0];
const flag = (name) => args.includes(name);
const option = (name) => {
  const i = args.indexOf(name);
  if (i < 0) return undefined;
  const value = args[i + 1];
  if (value === undefined || value.startsWith("--")) throw new Error(`${name} needs a value`);
  return value;
};
const options = (name) => args.flatMap((a, i) => (a === name && args[i + 1] !== undefined ? [args[i + 1]] : []));
const dryRun = flag("--dry-run");
const stateDir = option("--state") ?? join(process.env.RUNNER_TEMP ?? join(serviceDir, ".wrangler"), "deploy-state");

function generatedConfigPath(env) {
  return join(serviceDir, `wrangler.generated.${env}.json`);
}

function readState() {
  const file = join(stateDir, "state.json");
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {};
}

function saveState(key, value) {
  mkdirSync(stateDir, { recursive: true });
  const state = readState();
  state[key] = value;
  writeFileSync(join(stateDir, "state.json"), JSON.stringify(state, null, 2));
}

function setOutput(name, value) {
  if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `${name}=${value}\n`);
  console.log(`output ${name}=${value}`);
}

function mask(value) {
  // GitHub replaces every later occurrence of a masked value in the log with ***. The command itself is not shown.
  if (inActions) for (const line of String(value).split(/\r?\n/)) if (line.length > 0) process.stdout.write(`::add-mask::${line}\n`);
}

function warn(message) {
  console.log(inActions ? `::warning::${message}` : `warning: ${message}`);
}

function readEnvConfig(env, configPath = join(serviceDir, "wrangler.toml")) {
  return unstable_readConfig({ config: configPath, env });
}

// ---------------------------------------------------------------------------------------------------------------
// resources: D1 database, R2 buckets, audit and backup bucket rules, generated wrangler config

async function ensureBucket(name, create) {
  if (dryRun) return { name, created: false, dryRun: true };
  const got = await cf("GET", `/r2/buckets/${encodeURIComponent(name)}`);
  if (got.ok) return { name, created: false };
  if (got.status !== 404) throw new Error(`Checking R2 bucket ${name} failed: ${describe(got)}`);
  if (!create) throw new Error(`R2 bucket ${name} does not exist. Run the Deploy service workflow with provision ticked.`);
  must(await cf("POST", "/r2/buckets", { name }), `Creating R2 bucket ${name}`);
  console.log(`Created R2 bucket ${name}.`);
  return { name, created: true };
}

// The audit bucket's 90-day lock and expiry (owner guide step 7.4) and the backup bucket's 29-day lock and 30-day expiry
// (docs/owner/backups.md; threat-model review TM-03). `lock` and `lifecycle` are the two rules, with their days.
const AUDIT_RULES = { lock: auditLockRule(), lockDays: AUDIT_DAYS, lifecycle: auditLifecycleRule(), days: AUDIT_DAYS, guide: "owner guide step 7.4" };
const BACKUP_RULES = { lock: backupLockRule(), lockDays: BACKUP_LOCK_DAYS, lifecycle: backupLifecycleRule(), days: BACKUP_RETENTION_DAYS, guide: `${BACKUP_GUIDE}, step 2` };

async function ensureRule(kind, bucket, create, rules = AUDIT_RULES) {
  const id = kind === "lock" ? rules.lock.id : rules.lifecycle.id;
  const about = { kind, bucket, id, days: kind === "lock" ? rules.lockDays : rules.days, guide: rules.guide };
  const path = `/r2/buckets/${encodeURIComponent(bucket)}/${kind === "lock" ? "lock" : "lifecycle"}`;
  if (dryRun) {
    console.log(`[dry run] would ensure the ${kind} rule ${id} on ${bucket}`);
    return { ...about, action: "dry-run" };
  }
  const got = await cf("GET", path);
  if (!got.ok) {
    warn(`Could not read the ${kind} rules of ${bucket} (${describe(got)}). Set them in the dashboard (${rules.guide}).`);
    return { ...about, action: "failed", error: describe(got) };
  }
  const plan = kind === "lock" ? planLockRules(got.result?.rules, rules.lock) : planLifecycleRules(got.result?.rules, rules.lifecycle);
  if (plan.action === "conflict") warn(`The ${kind} rule ${id} on ${bucket} exists with other settings; it was left unchanged. Check it in the dashboard.`);
  if (plan.action !== "add") return { ...about, action: plan.action };
  if (!create) return { ...about, action: "missing" };
  const put = await cf("PUT", path, { rules: plan.rules });
  if (!put.ok) {
    warn(`Could not set the ${kind} rule ${id} on ${bucket} (${describe(put)}). Set it in the dashboard (${rules.guide}).`);
    return { ...about, action: "failed", error: describe(put) };
  }
  console.log(`Added the ${kind} rule ${id} on ${bucket}.`);
  return { ...about, action: "add" };
}

async function resources(env, create) {
  const config = readEnvConfig(env);
  const res = resourcesFromConfig(config, env);
  const record = { workerName: res.workerName, database: null, buckets: [], rules: [], generatedConfig: null, dryRun };
  try {
    let databaseId;
    let created = false;
    if (dryRun) {
      databaseId = res.database.configuredId ?? DRY_RUN_DATABASE_ID;
      console.log(`[dry run] would look up D1 database ${res.database.name}${create ? ` and create it in ${D1_LOCATION} if missing` : ""}`);
    } else {
      databaseId = await findDatabase(res.database.name);
      if (databaseId === null) {
        if (!create) throw new Error(`D1 database ${res.database.name} does not exist. Run the Deploy service workflow with provision ticked.`);
        databaseId = must(await cf("POST", "/d1/database", { name: res.database.name, primary_location_hint: D1_LOCATION }), `Creating D1 database ${res.database.name}`).uuid;
        created = true;
        console.log(`Created D1 database ${res.database.name}.`);
      }
    }
    // The database ID is not secret; it is recorded so the developer can add it to wrangler.toml if wanted.
    record.database = { name: res.database.name, id: databaseId, created };

    for (const bucket of res.buckets) {
      if (dryRun) console.log(`[dry run] would ensure R2 bucket ${bucket.name}`);
      record.buckets.push(await ensureBucket(bucket.name, create));
    }
    const audit = res.buckets.find((b) => b.binding === AUDIT_BINDING);
    if (!audit) throw new Error(`wrangler.toml [env.${env}] has no ${AUDIT_BINDING} bucket`);
    record.rules.push(await ensureRule("lock", audit.name, create));
    record.rules.push(await ensureRule("lifecycle", audit.name, create));

    // The encrypted backups (scripts/backup.mjs). Not in wrangler.toml on purpose: the Worker has no binding to it, so
    // a fault in the Worker can neither read nor delete backups. Its 30-day expiry is the backup retention (PLAN_V2 §6).
    const backups = backupBucketName(env);
    if (dryRun) console.log(`[dry run] would ensure R2 bucket ${backups}`);
    record.buckets.push(await ensureBucket(backups, create));
    record.rules.push(await ensureRule("lock", backups, create, BACKUP_RULES));
    record.rules.push(await ensureRule("lifecycle", backups, create, BACKUP_RULES));

    // The per-deploy config: wrangler.toml plus the database ID, next to wrangler.toml so relative paths resolve.
    const { rawConfig } = experimental_readRawConfig({ config: join(serviceDir, "wrangler.toml") });
    const generatedPath = generatedConfigPath(env);
    writeFileSync(generatedPath, JSON.stringify(withDatabaseId(rawConfig, env, res.database.name, databaseId), null, 2));
    const generated = readEnvConfig(env, generatedPath);
    const differences = configDifferences(config, generated);
    if (differences.length > 0) throw new Error(`the generated config differs from wrangler.toml in: ${differences.join(", ")}`);
    if (generated.d1_databases[0]?.database_id !== databaseId) throw new Error("the generated config does not carry the database ID");
    record.generatedConfig = generatedPath;
    console.log(`Wrote ${generatedPath} (wrangler.toml plus database_id ${databaseId}); it is used for this deploy only.`);
    if (dryRun) {
      rmSync(generatedPath);
      console.log("[dry run] removed it again.");
    }
    setOutput("config", generatedPath);
  } finally {
    saveState("resources", record);
  }
}

