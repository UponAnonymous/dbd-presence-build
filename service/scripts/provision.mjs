// check-config and summary

async function checkConfig(file) {
  const keysFile = option("--keys");
  let trustedKeys = [];
  if (keysFile && existsSync(keysFile)) trustedKeys = JSON.parse(readFileSync(keysFile, "utf8")).keys ?? [];
  const result = await inspectConfigResponse(readFileSync(file, "utf8"), { trustedKeys });
  console.log(
    result.ok
      ? `signed config document, kid ${result.kid}, expires ${result.expiresAt}; signature ${result.signatureChecked ? "verified with this run's public key" : "not verified here (no new public key in this run)"}`
      : result.reason,
  );
  process.exitCode = result.ok ? 0 : 1;
}

// The record of another service on the same domain must never change. It is checked against Cloudflare's own
// nameservers for the zone and a public resolver, before anything is changed and again at the end.
const ZONE_NAMESERVERS = ["augustus.ns.cloudflare.com", "cloe.ns.cloudflare.com"];

async function checkDns() {
  const smokeFile = option("--smoke");
  const results = [];
  const servers = [];
  for (const ns of ZONE_NAMESERVERS) {
    try {
      servers.push({ label: ns, ips: await new Resolver().resolve4(ns) });
    } catch (error) {
      results.push({ server: ns, ok: false, detail: `cannot resolve the nameserver itself (${error.code ?? error.message})` });
    }
  }
  servers.push({ label: "1.1.1.1", ips: ["1.1.1.1"] });
  for (const { label, ips } of servers) {
    const resolver = new Resolver({ timeout: 5000, tries: 2 });
    resolver.setServers(ips);
    try {
      const answers = [...new Set(await resolver.resolve4(PROTECTED_RECORD.name))].sort();
      const ok = answers.length === 1 && answers[0] === PROTECTED_RECORD.value;
      results.push({ server: label, ok, detail: ok ? answers[0] : `got ${answers.join(", ") || "no address"}, expected ${PROTECTED_RECORD.value} only` });
    } catch (error) {
      results.push({ server: label, ok: false, detail: `no answer (${error.code ?? error.message}), expected ${PROTECTED_RECORD.value}` });
    }
  }
  for (const r of results) {
    const line = `${PROTECTED_RECORD.name} unchanged (asked ${r.server})\t${r.ok ? "pass" : "fail"}\t${r.detail}`;
    if (smokeFile) appendFileSync(smokeFile, line + "\n");
    if (r.ok) console.log(`${PROTECTED_RECORD.name} via ${r.server}: ${r.detail}`);
    else console.log(inActions ? `::error title=Protected DNS record changed::${PROTECTED_RECORD.name} via ${r.server}: ${r.detail}. This workflow never edits DNS records; stop and check the record in the dashboard (arcavale.com → DNS → Records). It must be A ${PROTECTED_RECORD.value}, DNS only.` : `error: ${PROTECTED_RECORD.name} via ${r.server}: ${r.detail}`);
  }
  process.exitCode = results.every((r) => r.ok) ? 0 : 1;
}

function summary(env) {
  const smokeFile = option("--smoke");
  const outcomes = {};
  for (const pair of options("--outcome")) {
    const [step, result = ""] = pair.split("=");
    if (step) outcomes[step] = result;
  }
  const smoke = smokeFile && existsSync(smokeFile) ? parseSmokeResults(readFileSync(smokeFile, "utf8")) : [];
  process.stdout.write(renderSummary({ env, state: readState(), outcomes, smoke }) + "\n");
}

// ---------------------------------------------------------------------------------------------------------------

async function main() {
  const env = command === "check-config" || command === "check-dns" ? null : assertEnvironment(option("--env") ?? "");
  const create = flag("--create");
  switch (command) {
    case "resources":
      return resources(env, create);
    case "secrets":
      return secrets(env, create);
    case "workers-dev":
      return workersDev(env);
    case "pages":
      return pages(env, create);
    case "check-config":
      if (!args[1] || args[1].startsWith("--")) throw new Error("check-config needs the response body file");
      return checkConfig(args[1]);
    case "check-dns":
      return checkDns();
    case "summary":
      return summary(env);
    default:
      throw new Error("usage: node scripts/provision.mjs resources|secrets|workers-dev|pages|summary --env staging|production [--create] [--dry-run], or check-config <file>, or check-dns");
  }
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  console.log(inActions ? `::error::${message}` : `error: ${message}`);
  process.exitCode = 1;
});
