// pages: the Owner Panel's Pages project

async function pages(env, create) {
  const project = PAGES_PROJECTS[env];
  const panelName = unstable_readConfig({ config: join(panelDir, "wrangler.toml") }).name;
  if (panelName !== PAGES_PROJECTS.production) throw new Error(`panel/wrangler.toml names the project ${panelName}, expected ${PAGES_PROJECTS.production}`);
  const record = { project, created: false };
  try {
    if (dryRun) {
      console.log(`[dry run] would ensure the Pages project ${project} (production branch main)`);
    } else {
      const got = await cf("GET", `/pages/projects/${encodeURIComponent(project)}`);
      if (got.ok) {
        if (got.result?.production_branch !== "main") throw new Error(`the Pages project ${project} has production branch "${got.result?.production_branch}", not "main"; deploying would create a preview. Change it in the dashboard (Workers & Pages → ${project} → Settings → Build → Branch control).`);
        console.log(`Pages project ${project} exists.`);
      } else if (got.status === 404 || hasCode(got, 8000007)) {
        if (!create) throw new Error(`the Pages project ${project} does not exist. Run the workflow with provision ticked.`);
        must(await cf("POST", "/pages/projects", { name: project, production_branch: "main" }), `Creating the Pages project ${project}`);
        record.created = true;
        console.log(`Created Pages project ${project}.`);
      } else {
        must(got, `Reading the Pages project ${project}`);
      }
    }
    setOutput("project", project);
  } finally {
    saveState("pages", record);
  }
}

