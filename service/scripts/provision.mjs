// workers-dev: the Worker's workers.dev address and previews must be off (FR-ADM-02, gate V3.4)

async function workersDev(env) {
  const res = resourcesFromConfig(readEnvConfig(env), env);
  if (dryRun) {
    console.log(`[dry run] would check that ${res.workerName} has workers.dev and previews switched off`);
    return;
  }
  const record = { enabled: null, changed: false, url: null, accountSubdomain: "unknown" };
  try {
    const account = await cf("GET", "/workers/subdomain");
    const sub = account.ok ? account.result?.subdomain : null;
    if (sub) record.url = `https://${res.workerName}.${sub}.workers.dev`;
    // "none": the account has no workers.dev subdomain at all, so nothing can be served there.
    record.accountSubdomain = sub ? "known" : account.ok || account.status === 404 ? "none" : "unknown";
    if (record.accountSubdomain === "unknown") warn(`Could not read the account's workers.dev subdomain (${describe(account)}).`);
    const got = await cf("GET", `/workers/scripts/${encodeURIComponent(res.workerName)}/subdomain`);
    if (!got.ok && got.status === 404) {
      console.log(`${res.workerName} does not exist yet; nothing is served on workers.dev.`);
      record.enabled = false;
    } else {
      const state = must(got, "Reading the workers.dev setting");
      record.enabled = Boolean(state.enabled || state.previews_enabled);
      if (record.enabled) {
        must(await cf("POST", `/workers/scripts/${encodeURIComponent(res.workerName)}/subdomain`, { enabled: false, previews_enabled: false }), "Switching off workers.dev");
        record.changed = true;
        record.enabled = false;
        console.log(`Switched off workers.dev and previews for ${res.workerName}.`);
      } else {
        console.log(`workers.dev and previews are off for ${res.workerName}.`);
      }
    }
    setOutput("url", record.url ?? "");
    setOutput("account_subdomain", record.accountSubdomain);
  } finally {
    saveState("workersDev", record);
  }
}

