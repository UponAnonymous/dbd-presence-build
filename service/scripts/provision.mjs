// secrets

async function existingSecrets(workerName) {
  const r = await cf("GET", `/workers/scripts/${encodeURIComponent(workerName)}/secrets`);
  if (r.ok) return { workerExists: true, names: (r.result ?? []).map((s) => s.name) };
  if (r.status === 404 && (hasCode(r, 10007) || hasCode(r, 10090))) return { workerExists: false, names: [] };
  throw new Error(`Listing the secrets of ${workerName} failed: ${describe(r)}`);
}

function redact(text, secrets) {
  let out = String(text ?? "");
  for (const s of secrets) out = out.split(s).join("***");
  return out;
}

function generateAndStore(env, item) {
  const gen = spawnSync(process.execPath, [newSecretScript, item.kind, item.kid], { cwd: serviceDir, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  const secret = gen.stdout ?? "";
  const hide = secret.length > 0 ? valuesToMask(secret) : [];
  for (const v of hide) mask(v);
  if (gen.status !== 0 || secret.length === 0) throw new Error(`generating ${item.name} failed: ${redact(gen.stderr, hide).trim()}`);
  const spki = item.kind === "signing-key" ? publicKeyFromGeneratorOutput(gen.stderr, item.kid) : null;
  const put = spawnSync(process.execPath, [wranglerBin, "secret", "put", item.name, "--env", env], {
    cwd: serviceDir,
    input: secret,
    encoding: "utf8",
    stdio: ["pipe", "pipe", "pipe"],
  });
  process.stdout.write(redact(put.stdout, hide));
  process.stderr.write(redact(put.stderr, hide));
  if (put.status !== 0) throw new Error(`storing ${item.name} in Cloudflare failed (wrangler exit ${put.status})`);
  return { name: item.name, kid: item.kid, purpose: item.purpose, reason: item.reason, spki };
}

async function secrets(env, create) {
  const rotate = flag("--rotate");
  if (rotate && !create) throw new Error("--rotate needs --create (tick provision as well)");
  const config = readEnvConfig(env);
  const res = resourcesFromConfig(config, env);
  let existing;
  if (dryRun) {
    existing = { workerExists: false, names: (option("--assume-existing") ?? "").split(",").filter(Boolean) };
    console.log(`[dry run] assuming these secrets exist: ${existing.names.join(", ") || "(none)"}`);
  } else {
    existing = await existingSecrets(res.workerName);
  }
  const plan = planSecrets({ env, required: res.requiredSecrets, existing: existing.names, rotate, runNumber: option("--run-number") });
  const record = {
    workerExisted: existing.workerExists,
    generated: [],
    kept: plan.kept,
    refused: plan.refused,
    ownerMustEnter: plan.ownerMustEnter,
    unhandled: plan.unhandled,
    notCreated: [],
    dryRun,
  };
  for (const r of plan.refused) warn(`${r.name} was not replaced: ${r.reason}`);
  try {
    for (const item of plan.generate) {
      if (dryRun || !create) {
        console.log(`${dryRun ? "[dry run] would generate" : "Missing (provision is off, not generated):"} ${item.name} as ${item.kid}`);
        if (!dryRun) record.notCreated.push(item.name);
        continue;
      }
      record.generated.push(generateAndStore(env, item));
      console.log(`Stored ${item.name} (${item.kid}).`);
    }
  } finally {
    const keys = trustedKeyEntries(record.generated);
    if (keys.length > 0) {
      mkdirSync(stateDir, { recursive: true });
      writeFileSync(join(stateDir, `public-keys-${env}.json`), JSON.stringify({ environment: env, list: env, keys }, null, 2) + "\n");
    }
    saveState("secrets", record);
  }
  if (!dryRun && plan.generate.length > 0 && create) {
    const after = await existingSecrets(res.workerName);
    const absent = plan.generate.map((g) => g.name).filter((n) => !after.names.includes(n));
    if (absent.length > 0) throw new Error(`Cloudflare does not list these secrets after storing them: ${absent.join(", ")}`);
  }
  for (const m of plan.ownerMustEnter) console.log(`Owner must enter ${m.name}: ${m.source}`);
  for (const n of plan.unhandled) warn(`${n} is required by wrangler.toml but this workflow does not know how to make it.`);
  setOutput("ready", readyToDeploy(plan) && record.notCreated.length === 0 && !dryRun ? "true" : "false");
}

