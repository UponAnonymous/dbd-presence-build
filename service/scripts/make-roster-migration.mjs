// Writes migrations/0005_roster_and_default_pack.sql (PLAN_V2_S5B §2.2, S5b-2 and S5b-3; owner decision D35).
//
//   node scripts/make-roster-migration.mjs        (from service/)
//
// The seed rows come from tests/fixtures/roster/seed.json (code, id, role) and the names and aliases from the app's
// vocabulary (src/DbdPresence.Vision/Vocabulary/vocabulary.en.json), so the service starts with exactly the characters
// the app already embeds. test/roster.test.ts checks that the applied migration and both files agree. Run it again only
// before migration 0005 is first applied anywhere: migrations are forward-only, and a later change needs a new file.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "..");
const seed = JSON.parse(readFileSync(join(root, "tests", "fixtures", "roster", "seed.json"), "utf8"));
const vocabulary = JSON.parse(readFileSync(join(root, "src", "DbdPresence.Vision", "Vocabulary", "vocabulary.en.json"), "utf8"));

const byId = new Map([...vocabulary.killers, ...vocabulary.survivors].map((e) => [e.id, e]));
const sql = (text) => `'${String(text).replaceAll("'", "''")}'`;

const rows = seed.characters.map((c) => {
  const entry = byId.get(c.id);
  if (!entry || entry.code !== c.code) throw new Error(`seed ${c.code} ${c.id} is not in the vocabulary with that code`);
  const aliases = (entry.aliases ?? []).map((a) => ({ name: a.name, seenOnScreen: a.seenOnScreen }));
  return `  (${sql(c.code)}, ${sql(c.id)}, ${sql(c.role)}, ${sql(entry.name)}, ${sql(entry.name)}, ${sql(JSON.stringify(aliases))}, NULL, 'seed', 0, NULL)`;
});

const text = `-- Character roster (V2-S5b: PLAN_V2_S5B §2.1–2.3, S5b-2; owner decision D35), the default pack flag and the source hash
-- of pack entries (S5b-3). Forward-only: never edit an applied migration; add a new numbered file.
-- GENERATED by scripts/make-roster-migration.mjs from tests/fixtures/roster/seed.json and the vocabulary's names.
--
-- The roster changes in three ways only: the owner adds, renames or removes a character in the Owner Panel; or the
-- owner's own app reports a character name it read in the game that is not in the vocabulary, and after the same folded
-- name was seen in 3 separate matches the service adds it (D35). Nothing is ever fetched from a third party.
-- Rows stay small (D18): a character row is about 150 bytes; sightings are capped and kept 30 days.

-- One row per character. The code is the game's portrait file prefix and the id the pack slug; neither ever changes, and
-- no row is ever deleted: a removed character keeps its row with withdrawn_at set and stays in the signed roster as
-- withdrawn (the app never forgets a code or an id). aliases is JSON [{ "name", "seenOnScreen" }].
CREATE TABLE roster_characters (
  code            TEXT PRIMARY KEY CHECK (length(code) = 3 AND code GLOB '[KS][0-9][0-9]'),
  id              TEXT NOT NULL UNIQUE,
  role            TEXT NOT NULL CHECK (role IN ('killer', 'survivor')),
  display_name    TEXT NOT NULL,
  screen_name     TEXT NOT NULL,
  aliases         TEXT NOT NULL DEFAULT '[]',
  licensed_holder TEXT,
  source          TEXT NOT NULL CHECK (source IN ('seed', 'owner', 'auto')),
  added_at        INTEGER NOT NULL,
  withdrawn_at    INTEGER
) WITHOUT ROWID;

-- The signed roster: one row per content version, the exact payload the document carries. prev_version is UNIQUE, so two
-- changes made against the same version cannot both commit (the loser re-reads and tries again, as with pack_index).
-- signed_at is the issuedAt of the document served now: set when the content changes and moved forward by the daily cron
-- once it is 7 days old (the weekly re-sign). The newest 3 versions are kept.
CREATE TABLE roster_versions (
  version      INTEGER PRIMARY KEY,
  prev_version INTEGER NOT NULL UNIQUE,
  payload      TEXT NOT NULL,
  created_at   INTEGER NOT NULL,
  signed_at    INTEGER NOT NULL
);

-- Sightings reported by the owner's app (D35): only the folded name, the role and a random id per match; no player
-- name, no image, no user id. One row per name, role and match, so a match counts once however often it is reported.
CREATE TABLE roster_sightings (
  folded   TEXT NOT NULL,
  role     TEXT NOT NULL CHECK (role IN ('killer', 'survivor')),
  match_id TEXT NOT NULL,
  seen_at  INTEGER NOT NULL,
  PRIMARY KEY (folded, role, match_id)
) WITHOUT ROWID;

-- Folded names the owner removed (Undo, D35): never added automatically again until the owner allows the name.
CREATE TABLE roster_blocks (
  folded     TEXT PRIMARY KEY,
  blocked_at INTEGER NOT NULL
) WITHOUT ROWID;

-- The owner marks their own app account in the panel; only such accounts may report sightings (D35: friends' apps never report).
ALTER TABLE users ADD COLUMN roster_reporter INTEGER NOT NULL DEFAULT 0 CHECK (roster_reporter IN (0, 1));

-- S5b-3: one owner pack per channel may be the default pictures for characters, and an entry may carry the SHA-256 of the
-- file the owner uploaded before the lossless clean-up.
ALTER TABLE packs ADD COLUMN is_default INTEGER NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1));
ALTER TABLE published_packs ADD COLUMN is_default INTEGER NOT NULL DEFAULT 0;
ALTER TABLE pack_entries ADD COLUMN source_sha256 TEXT;
ALTER TABLE published_entries ADD COLUMN source_sha256 TEXT;

-- The reviewed seed: ${rows.length} characters.
INSERT INTO roster_characters (code, id, role, display_name, screen_name, aliases, licensed_holder, source, added_at, withdrawn_at) VALUES
${rows.join(",\n")};
`;

writeFileSync(join(import.meta.dirname, "..", "migrations", "0005_roster_and_default_pack.sql"), text);
console.log(`wrote migrations/0005_roster_and_default_pack.sql with ${rows.length} characters`);
